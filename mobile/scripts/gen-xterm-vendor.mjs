// Inlines xterm.js, its CSS and the fit addon into
// src/terminal/xterm-vendor.generated.ts, so the terminal WebView's HTML is
// one string in the JS bundle: no CDN, works offline, and ships in an OTA
// (a bundled .html asset would need a native rebuild to change, and WebView
// asset loading differs per platform). Runs from `postinstall`, so the file
// always matches the xterm version in package-lock; it's gitignored.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(join(here, '../package.json'))
const OUTPUT = join(here, '../src/terminal/xterm-vendor.generated.ts')

const read = (spec) => readFileSync(require.resolve(spec), 'utf8')
const pkg = (name) => JSON.parse(readFileSync(require.resolve(`${name}/package.json`), 'utf8')).version

// The strings land inside <script>/<style> tags; a literal closing tag in
// the source would end the element early.
const forScript = (s) => s.replace(/<\/script/gi, '<\\/script')
const forStyle = (s) => s.replace(/<\/style/gi, '<\\/style')

const source = `// GENERATED by scripts/gen-xterm-vendor.mjs (postinstall) — do not edit.
// @xterm/xterm ${pkg('@xterm/xterm')}, @xterm/addon-fit ${pkg('@xterm/addon-fit')}
export const XTERM_JS: string = ${JSON.stringify(forScript(read('@xterm/xterm/lib/xterm.js')))}
export const XTERM_CSS: string = ${JSON.stringify(forStyle(read('@xterm/xterm/css/xterm.css')))}
export const FIT_JS: string = ${JSON.stringify(forScript(read('@xterm/addon-fit/lib/addon-fit.js')))}
`

mkdirSync(dirname(OUTPUT), { recursive: true })
writeFileSync(OUTPUT, source)
console.log(`xterm vendor: ${(source.length / 1024).toFixed(0)} KB → ${OUTPUT}`)
