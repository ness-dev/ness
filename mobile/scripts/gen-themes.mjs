// Generates src/themes.generated.ts from the desktop's
// src/renderer/styles.css, so the app's palettes are the desktop's built-in
// themes exactly. Run from mobile/: `node scripts/gen-themes.mjs`.
//
// Cascade, same as the browser: the `@theme { … }` block is the default
// (Dark); each `[data-theme="<id>"] { … }` block overrides tokens on top of
// it. `var(--color-x)` values resolve within the same theme.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const css = readFileSync(join(here, '../../src/renderer/styles.css'), 'utf8')

function blockAfter(start) {
  const open = css.indexOf('{', start)
  let depth = 0
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i)
  }
  throw new Error('unbalanced block')
}

function colorVars(block) {
  const out = {}
  for (const m of block.matchAll(/--color-([a-z-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim()
  return out
}

const base = colorVars(blockAfter(css.indexOf('@theme {')))
const themes = { dark: { ...base } }
for (const m of css.matchAll(/^\[data-theme="([a-z0-9-]+)"\]\s*\{/gm)) {
  themes[m[1]] = { ...base, ...(themes[m[1]] ?? {}), ...colorVars(blockAfter(m.index)) }
}

const resolve = (t, v, depth = 0) => {
  const ref = /^var\(--color-([a-z-]+)\)$/.exec(v)
  if (!ref || depth > 5) return v
  return resolve(t, t[ref[1]] ?? v, depth + 1)
}
for (const t of Object.values(themes)) for (const k of Object.keys(t)) t[k] = resolve(t, t[k])

const camel = (k) => k.replace(/-([a-z])/g, (_, ch) => ch.toUpperCase())
const out = {}
for (const [id, t] of Object.entries(themes)) {
  out[id] = Object.fromEntries(Object.entries(t).filter(([, v]) => /^#|^rgb/.test(v)).map(([k, v]) => [camel(k), v]))
}

writeFileSync(
  join(here, '../src/themes.generated.ts'),
  `// GENERATED by scripts/gen-themes.mjs from src/renderer/styles.css — do not
// edit; regenerate when the desktop's themes change.
export const BUILT_IN_PALETTES: Record<string, Record<string, string>> = ${JSON.stringify(out, null, 2)}
`
)
console.log(Object.keys(out).length, 'themes:', Object.keys(out).join(', '))
console.log('keys (dark):', Object.keys(out.dark).join(' '))
